#!/usr/bin/env python3
"""Generate Lambda/native binding contracts from one manifest (D3.5.1)."""
import argparse
import hashlib
import json
from pathlib import Path
import re


SCALARS = {
    'bool': 'BOOL', 'i8': 'I8', 'u8': 'U8', 'i16': 'I16', 'u16': 'U16',
    'i32': 'I32', 'u32': 'U32', 'i64': 'I64', 'u64': 'U64', 'f32': 'F32', 'f64': 'F64',
}


def generate(manifest):
    if manifest['format'] != 1 or not isinstance(manifest['revision'], int):
        raise ValueError('unsupported binary binding manifest format/revision')
    records = manifest['records']
    by_name = {record['name']: record for record in records}
    if len(by_name) != len(records):
        raise ValueError('duplicate binary schema name')
    payload = {key: manifest[key] for key in ('format', 'revision', 'records')}
    revision = hashlib.sha256(json.dumps(payload, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    version_symbol = manifest['version_symbol']
    cpp = ['// Generated by utils/generate_binary_bindings.py; edit the manifest.',
           f'#include "{Path(manifest["outputs"]["version"]).name}"', '']
    script = ['// Generated by utils/generate_binary_bindings.py; edit the manifest.',
              '// Native layouts expose selected fields; the walker owns tree links.']
    emitted = set()
    for record in records:
        name, host, symbol = record['name'], record['cpp_type'], record['symbol']
        if not all(re.fullmatch(r'[A-Za-z_]\w*', value) for value in (name, host, symbol)):
            raise ValueError('binary binding names must be identifiers')
        if not record['fields'] or len({field['name'] for field in record['fields']}) != len(record['fields']):
            raise ValueError('binary bindings require distinct fields')
        entries, checks = [], []
        script.append(f"pub type {name} : binary & {{layout: 'native', binding: '{record['binding']}', version: '{revision}'}} {{")
        for field in record['fields']:
            member = field.get('member', field['name'])
            if member != field['name'] or not re.fullmatch(r'[A-Za-z_]\w*', member):
                raise ValueError('binary binding members must retain their declared name')
            logical = field['type']
            nullable = logical.endswith('?')
            base = logical.rstrip('?')
            pointer = field.get('pointer', False)
            span = re.fullmatch(r'(\w+)\[([A-Za-z_]\w*|[0-9][0-9_]*)\]', base)
            if span:
                base, count = span.groups()
                capacity = field.get('capacity')
                if not pointer or not capacity or not re.fullmatch(r'[A-Za-z_]\w*', capacity):
                    raise ValueError('native spans require a pointer and host capacity member')
            annotation = " & {pointer: 'native'}" if pointer else ''
            script.append(f"    {member}: {logical}{annotation},")
            if span:
                if base in by_name:
                    if base not in emitted:
                        raise ValueError('span record targets must precede their users')
                    target, kind = '&' + by_name[base]['symbol'], 'BINARY_FIELD_RECORD'
                    target_type = by_name[base]['cpp_type']
                    checks.append(f'static_assert(BinarySchemaSameType<BinarySchemaPointer<decltype((({host}*)nullptr)->{member})>::Target, {target_type}>::value, "binary span target type changed");')
                elif base in SCALARS or base == 'binary':
                    target, kind = 'nullptr', 'BINARY_FIELD_' + SCALARS.get(base, 'U8')
                    checks.append(f'static_assert(BinarySchemaScalarKind<BinarySchemaPointer<decltype((({host}*)nullptr)->{member})>::Target>::kind == {kind}, "binary span scalar representation changed");')
                else:
                    raise ValueError('unsupported span element type')
                native_count = count if not count[0].isdigit() else capacity
                arguments = f'{host}, {member}, {native_count}, {capacity}'
                if base == 'binary':
                    entry = f'BINARY_SCHEMA_BYTES({arguments}, {str(nullable).lower()})'
                else:
                    entry = f'BINARY_SCHEMA_SPAN({arguments}, {kind}, {target}, {str(nullable).lower()})'
            elif base in by_name:
                if base not in emitted:
                    raise ValueError('nested binary schemas must precede their users')
                target = '&' + by_name[base]['symbol']
                actual = f'BinarySchemaPointer<decltype((({host}*)nullptr)->{member})>::Target' if pointer else f'decltype((({host}*)nullptr)->{member})'
                checks.append(f'static_assert(BinarySchemaSameType<{actual}, {by_name[base]["cpp_type"]}>::value, "binary binding target type changed");')
                if pointer:
                    entry = f'BINARY_SCHEMA_REFERENCE({host}, {member}, {target}, {str(nullable).lower()})'
                else:
                    if nullable:
                        raise ValueError('inline binary records cannot be nullable')
                    entry = f'BINARY_SCHEMA_RECORD({host}, {member}, {target})'
            elif base in SCALARS and not pointer and not nullable:
                kind = 'BINARY_FIELD_' + SCALARS[base]
                entry = f'BINARY_SCHEMA_MEMBER({host}, {member}, {kind})'
                checks.append(f'static_assert(BinarySchemaScalarKind<decltype((({host}*)nullptr)->{member})>::kind == {kind}, "binary binding scalar representation changed");')
            elif base in ('string', 'binary', 'any') and not pointer:
                entry = f'BINARY_SCHEMA_ITEM({host}, {member}, &TYPE_{base.upper()}, {str(nullable).lower()})'
                checks.append(f'static_assert(BinarySchemaSameType<decltype((({host}*)nullptr)->{member}), Item>::value, "binary boxed field representation changed");')
            else:
                raise ValueError(f'unsupported native manifest field {name}.{member}: {logical}')
            entries.append('    ' + entry + ',')
        # Lambda object declarations require separators, without a trailing comma.
        script[-1] = script[-1].rstrip(',')
        script.extend(['}', ''])
        cpp.extend(checks)
        cpp.extend([f'const BinarySchemaField {symbol}_fields[] = {{', *entries, '};',
                    f'const BinarySchema {symbol} = {{"{host}", sizeof({host}), {symbol}_fields,',
                    f'    sizeof({symbol}_fields) / sizeof({symbol}_fields[0]), BINARY_SCHEMA_NATIVE,',
                    f'    "{record["binding"]}", nullptr, BINARY_SCHEMA_BINDING_ABI, {version_symbol}}};', ''])
        emitted.add(name)
    for name, fields in manifest.get('schema_sets', {}).items():
        if any(value not in by_name for value in fields.values()):
            raise ValueError('schema set contains an unknown record')
        script.append('pub fn ' + name + '() => {' + ', '.join(f'{key}: {value}' for key, value in fields.items()) + '}')
    version = ['// Generated by utils/generate_binary_bindings.py; edit the manifest.',
               '#pragma once', f'inline constexpr char {version_symbol}[] = "{revision}";', '']
    return dict(zip(('cpp', 'lambda', 'version'), ('\n'.join(cpp), '\n'.join(script) + '\n', '\n'.join(version))))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('manifest', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    manifest = json.loads(args.manifest.read_text())
    for kind, content in generate(manifest).items():
        target = root / manifest['outputs'][kind]
        if target.is_file() and target.read_text() == content:
            continue
        if args.check:
            raise SystemExit(f'binary binding output is stale: {target.relative_to(root)}')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)


if __name__ == '__main__':
    main()
