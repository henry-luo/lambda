#!/usr/bin/env python3
"""Generate UAX #50 properties from Unicode VerticalOrientation.txt."""

import hashlib
from pathlib import Path
import re
from unicode_generator import codepoint_range, run_generator

ROOT = Path(__file__).resolve().parent.parent
VALUES = {"R": 0, "U": 1, "Tu": 2, "Tr": 3}


def generate(source):
    version = re.search(r"VerticalOrientation-([\d.]+)\.txt", source)
    if not version:
        raise ValueError("expected a Unicode VerticalOrientation source")
    values = bytearray(0x110000)
    for span, kind in re.findall(r"# @missing:\s*([\dA-F.]+);\s*(\w+)", source):
        first, end = codepoint_range(span)
        values[first:end] = bytes([VALUES[kind]]) * (end - first)
    for line in source.splitlines():
        record = line.split("#", 1)[0].strip()
        if not record:
            continue
        span, kind = (part.strip() for part in record.split(";"))
        first, end = codepoint_range(span)
        if not 0 <= first < end <= len(values):
            raise ValueError("invalid Unicode property range")
        values[first:end] = bytes([VALUES[kind]]) * (end - first)
    ranges = []
    first = 0
    for end in range(1, len(values) + 1):
        if end < len(values) and values[first] == values[end]:
            continue
        if values[first]:
            ranges.append((first, end - 1, values[first]))
        first = end
    lines = [
        "// generated by utils/generate_unicode_vertical.py; do not edit.",
        f"// Unicode {version[1]} VerticalOrientation.txt; SHA-256: {hashlib.sha256(source.encode()).hexdigest()}",
        f"// source: https://www.unicode.org/Public/{version[1]}/ucd/VerticalOrientation.txt",
        "// Unicode data license: lib/UNICODE_LICENSE.txt (https://www.unicode.org/license.txt).",
        "// unlisted code points have Vertical_Orientation=R, including @missing defaults.",
        "static const UtfPropertyRange utf_vertical_non_rotated_ranges[] = {",
    ]
    names = {1: "UTF_VERTICAL_UPRIGHT", 2: "UTF_VERTICAL_TRANSFORMED_UPRIGHT", 3: "UTF_VERTICAL_TRANSFORMED_ROTATED"}
    lines.extend(f"    {{0x{first:04X}, 0x{last:04X}, {names[value]}}}," for first, last, value in ranges)
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    run_generator(generate, __doc__, ROOT / "lib/utf_vertical_data.h", "UNICODE_VERTICAL",
                  "Unicode vertical data differs; regenerate the header")
