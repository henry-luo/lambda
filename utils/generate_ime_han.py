#!/usr/bin/env python3
"""Generate the IME user-word Han pattern from checksum-pinned Unicode data."""

import argparse
import json
from pathlib import Path

from prepare_ime_chinese import HanScript, LOCK_PATH, ROOT, digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=ROOT / "temp/ime_sources")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    lock = json.loads(LOCK_PATH.read_bytes())
    source = lock["sources"]["unihan"]
    files = {}
    for name in ("Scripts.txt", "LICENSE"):
        raw = (args.source_dir / "unihan" / name).read_bytes()
        if digest(raw) != source["files"][name]["sha256"]:
            parser.error(f"pinned Unicode checksum mismatch: {name}")
        files[name] = raw
    ranges = HanScript(files["Scripts.txt"]).ranges
    atoms = [json.dumps(chr(start), ensure_ascii=False) +
             (" to " + json.dumps(chr(end), ensure_ascii=False) if start != end else "")
             for start, end in ranges]
    header = f"// generated by utils/generate_ime_han.py; Unicode {source['revision']}, Script=Han.\n"
    header += f"// Scripts.txt SHA-256: {digest(files['Scripts.txt'])}\n"
    header += "\n".join("// " + line if line else "//" for line in files["LICENSE"].decode().splitlines()) + "\n\n"
    generated = (header + "type word = \\((\n    " + " |\n    ".join(atoms) +
                 ")+)\n\npub fn valid(value: string) bool => value is word\n").encode()
    path = ROOT / "lmd/package/ime/chinese/han.ls"
    if args.write:
        path.write_bytes(generated)
    elif not path.exists() or path.read_bytes() != generated:
        parser.exit(1, "IME Han pattern differs; run with --write\n")
    print(f"IME Han pattern: {len(ranges)} pinned ranges verified")


if __name__ == "__main__":
    main()
