#!/usr/bin/env python3
"""Generate Intl.Locale likely-subtag lookup data from pinned Unicode CLDR 48."""

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SOURCE = "https://raw.githubusercontent.com/unicode-org/cldr-json/48.0.0/cldr-json/cldr-core/supplemental/likelySubtags.json"
SHA256 = "38345946ad457213fb39e9645ab50f36b61681bf674b2eef2979a3b58d04afc8"


def generate(source):
    if hashlib.sha256(source).hexdigest() != SHA256:
        raise ValueError("expected the pinned CLDR 48 likelySubtags.json")
    data = json.loads(source)["supplemental"]
    lines = [
        "// generated by utils/generate_js_locale_data.py; do not edit.",
        "// Unicode CLDR 48; Copyright (c) 1991-2026 Unicode, Inc.",
        "// SPDX-License-Identifier: Unicode-3.0; see ../../lib/UNICODE_LICENSE.txt.",
        f"// source: {SOURCE}",
        f"// source SHA-256: {SHA256}",
        "struct JsIntlLikelySubtag { const char* source; const char* target; };",
        "static const JsIntlLikelySubtag js_intl_likely_subtags[] = {",
    ]
    for key, value in sorted(data["likelySubtags"].items()):
        language, script, region = value.split("-")
        if not (2 <= len(language) <= 8 and len(script) == 4 and 2 <= len(region) <= 3):
            raise ValueError(f"invalid likely-subtag target: {value}")
        lines.append(f'    {{"{key}", "{value}"}},')
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "lambda/js/js_intl_likely_subtags.h")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(args.source.read_bytes())
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit("Intl.Locale likely-subtag data is stale")
    else:
        args.output.write_text(result)


if __name__ == "__main__":
    main()
