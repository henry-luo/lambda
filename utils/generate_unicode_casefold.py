#!/usr/bin/env python3
"""Generate single-code-point fold cycles from Unicode CaseFolding.txt."""

import hashlib
from pathlib import Path
import re
from unicode_generator import run_generator


ROOT = Path(__file__).resolve().parent.parent


def generate(source):
    version = re.search(r"CaseFolding-([\d.]+)\.txt", source)
    if not version:
        raise ValueError("expected a Unicode CaseFolding source")
    parents = {}

    def root(codepoint):
        parents.setdefault(codepoint, codepoint)
        while parents[codepoint] != codepoint:
            codepoint = parents[codepoint]
        return codepoint

    for line in source.splitlines():
        record = line.split("#", 1)[0].strip()
        if not record:
            continue
        codepoint, status, mapping, *_ = (part.strip() for part in record.split(";"))
        # Full and Turkic folds have different semantics from Unicode simple folding.
        if status not in ("C", "S"):
            continue
        values = mapping.split()
        if len(values) != 1:
            raise ValueError("simple folding must map one code point")
        left, right = root(int(codepoint, 16)), root(int(values[0], 16))
        parents[left] = right
    groups = {}
    for codepoint in parents:
        groups.setdefault(root(codepoint), []).append(codepoint)
    cycles = []
    for group in groups.values():
        group.sort()
        cycles.extend((cp, group[(i + 1) % len(group)]) for i, cp in enumerate(group))
    cycles.sort()
    lines = [
        "// generated by utils/generate_unicode_casefold.py; do not edit.",
        f"// Unicode {version[1]} CaseFolding.txt; SHA-256: {hashlib.sha256(source.encode()).hexdigest()}",
        f"// source: https://www.unicode.org/Public/{version[1]}/ucd/CaseFolding.txt",
        "// Unicode data license: lib/UNICODE_LICENSE.txt (https://www.unicode.org/license.txt).",
        "// common/simple equivalence cycles; no normalization, full expansion or Turkic mapping.",
        "static const struct { uint32_t codepoint, next; } utf8_simple_fold_cycles[] = {",
    ]
    lines.extend(f"    {{0x{codepoint:04X}, 0x{next_cp:04X}}}," for codepoint, next_cp in cycles)
    return "\n".join(lines + ["};", ""])


def main():
    run_generator(generate, __doc__, ROOT / "lambda/core/utf_simple_casefold.inc", "UNICODE_CASEFOLD",
                  "Unicode simple-fold data differs; regenerate the include")


if __name__ == "__main__":
    main()
