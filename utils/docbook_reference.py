#!/usr/bin/env python3
"""Pinned xslTNG oracle and resource generation for lambda.doc.docbook."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import urllib.request
import zipfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "lmd/package/doc/docbook"
CACHE = ROOT / "temp/docbook-upstream"
MANIFEST = PACKAGE / "upstream.json"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def literal(value):
    if isinstance(value, dict):
        return "{" + ",".join("[" + json.dumps(key) + "]:" + literal(item)
                              for key, item in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ",".join(literal(item) for item in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def locale_instruction(node):
    kind = node.tag.rsplit("}", 1)[-1]
    if kind == "text":
        return {"kind": kind, "text": node.text or ""}
    if kind == "content":
        return {"kind": kind}
    if kind == "token":
        return {"kind": kind, "key": node.attrib["key"]}
    if kind == "repeat":
        return {"kind": kind, "nodes": [locale_instruction(child) for child in node]}
    raise ValueError("Unsupported locale list instruction: " + node.tag)


def inline_templates(source):
    namespace = "{http://www.w3.org/1999/XSL/Transform}"
    result = {}
    for template in ET.parse(source).getroot().findall(namespace + "template"):
        match = template.get("match", "")
        if not re.fullmatch(r"db:[a-z0-9]+", match) or len(template) != 1:
            continue
        call = template[0]
        if call.tag != namespace + "call-template" or call.get("name") != "t:inline":
            continue
        spec = {"tag": "span", "classed": True, "class_attr": False}
        valid = True
        for parameter in call:
            key, value = parameter.get("name"), parameter.get("select", "")
            if key == "namemap" and re.fullmatch(r"'[a-z0-9]+'", value):
                spec["tag"] = value[1:-1]
            elif key == "namemap" and re.fullmatch(
                    r"if\s*\(fp:in-verbatim\(\.\)\)\s*then\s*'span'\s*else\s*'code'", value):
                spec.update(tag="code", verbatim_tag="span")
            elif key == "local-name-as-class" and value in {"true()", "false()"}:
                spec["classed"] = value == "true()"
            elif key == "class" and value == "@class":
                spec["class_attr"] = True
            else:
                valid = False
        if valid:
            result[match[3:]] = spec
    return result


def distribution(fetch=False):
    manifest = json.loads(MANIFEST.read_text())
    archive = CACHE / manifest["distribution"]["filename"]
    if not archive.exists():
        if not fetch:
            raise SystemExit("Missing oracle distribution; run with --fetch first")
        CACHE.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(manifest["distribution"]["url"], timeout=60) as response:
            archive.write_bytes(response.read())
    if digest(archive) != manifest["distribution"]["sha256"]:
        raise SystemExit("xslTNG distribution hash mismatch")
    target = CACHE / ("docbook-xslTNG-" + manifest["version"])
    if not target.exists():
        with zipfile.ZipFile(archive) as source:
            for name in source.namelist():
                if Path(name).is_absolute() or ".." in Path(name).parts:
                    raise SystemExit("Unexpected archive path")
            source.extractall(CACHE)
    return target


def resources(source):
    manifest = json.loads(MANIFEST.read_text())
    for item in manifest["translation_inputs"]:
        if digest(source / item["path"]) != item["sha256"]:
            raise SystemExit("Translation input hash mismatch: " + item["path"])
    entries = []
    for item in manifest["resources"]:
        original = source / item["source"]
        if digest(original) != item["sha256"]:
            raise SystemExit("Resource hash mismatch: " + item["source"])
        destination = PACKAGE / "resources/xsltng" / item["path"]
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(original, destination)
        entries.append({"path": item["path"], "media_type": item["media_type"],
                        "text": original.read_text(), "sha256": item["sha256"]})
    shutil.copyfile(source / "LICENSE", PACKAGE / "LICENSE.xsltng")
    code = "// Generated by utils/docbook_reference.py --resources; upstream assets are unmodified.\n"
    code += "pub let ASSETS = [\n" + ",\n".join(
        "    {" + ",".join(key + ":" + json.dumps(value, ensure_ascii=False)
                           for key, value in entry.items()) + "}"
        for entry in entries) + "\n]\n"
    external = re.findall(r'@import\s+url\("(https?://[^\"]+)"\)', entries[0]["text"])
    code += "pub let EXTERNAL_STYLESHEETS = " + json.dumps(external) + "\n"
    (PACKAGE / "resources.ls").write_text(code)
    stylesheet = (source / "xslt/modules/functions.xsl").read_text()
    table = re.search(r'<xsl:variable name="vp:gidmap".*?select="(.*?)"', stylesheet, re.S)
    if not table:
        raise SystemExit("Missing upstream generated-ID map")
    pairs = re.findall(r"'([^']+)'\s*:\s*'([^']+)'", table.group(1))
    (PACKAGE / "ids.ls").write_text(
        "// Generated from xslTNG 2.8.5 modules/functions.xsl vp:gidmap.\n"
        "pub let ABBREVIATIONS = {" + ", ".join(
            "[" + json.dumps(key) + "]:" + json.dumps(value) for key, value in pairs) + "}\n")
    locale = ET.parse(source / "xslt/locale/en.xml").getroot()
    ns = "{http://docbook.org/ns/docbook/l10n}"
    tokens = {node.attrib["key"]: "".join(node.itertext()) for node in locale.find(ns + "gentext")}
    lists = {node.attrib["name"]: [[locale_instruction(child) for child in item] for item in node]
             for node in locale.findall(ns + "list")}
    (PACKAGE / "locale.ls").write_text(
        "// Generated from pinned xslTNG xslt/locale/en.xml; lt:text whitespace is significant.\n"
        "pub let TOKENS = " + literal(tokens) + "\n"
        "pub let LISTS = " + literal(lists) + "\n")
    (PACKAGE / "inlines.ls").write_text(
        "// Generated from the finite t:inline wrapper forms in pinned xslTNG modules/inlines.xsl.\n"
        "pub let TEMPLATES = " + literal(inline_templates(source / "xslt/modules/inlines.xsl")) + "\n")


def transform(source, fixture, output, parameters):
    manifest = json.loads(MANIFEST.read_text())
    jar = source / ("libs/lib/Saxon-HE-" + manifest["oracle"]["version"] + ".jar")
    if digest(jar) != manifest["oracle"]["jar_sha256"]:
        raise SystemExit("Reference processor hash mismatch")
    java = os.environ.get("JAVA", "java")
    classpath = os.pathsep.join([str(source / "libs/*"), str(source / "libs/lib/*")])
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = ROOT / "temp/docbook-reference/java"
    temporary.mkdir(parents=True, exist_ok=True)
    args = [java, "-Djava.io.tmpdir=" + str(temporary), "-cp", classpath,
            "org.docbook.xsltng.Main", "-s:" + str(fixture.resolve()), "-o:" + str(output.resolve()),
            "persistent-toc=false", "verbatim-syntax-highlighter=none"]
    subprocess.run(args + parameters, cwd=ROOT, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fetch", action="store_true")
    parser.add_argument("--resources", action="store_true")
    parser.add_argument("--input", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--param", action="append", default=[])
    args = parser.parse_args()
    source = distribution(args.fetch)
    if args.resources:
        resources(source)
    if args.input:
        if not args.output:
            parser.error("--input requires --output")
        transform(source, args.input, args.output, args.param)
    print("Verified DocBook xslTNG distribution", source.name)


if __name__ == "__main__":
    main()
