"""Record WebRTC availability as a dependency of the runtime object."""

import json
from pathlib import Path
from tempfile import TemporaryDirectory

from split_paths import optional_library_available


ROOT = Path(__file__).resolve().parents[1]


def main():
    libraries = json.loads((ROOT / "build_lambda_config.json").read_text())["libraries"]
    libraries_by_name = {library["name"]: library for library in libraries}
    datachannel = libraries_by_name["sync-datachannel"]
    providers = (datachannel, libraries_by_name["sync-juice"], libraries_by_name["sync-usrsctp"])
    available = (ROOT / datachannel["include"] / "rtc/rtc.h").is_file() and all(
        optional_library_available({**library, "lib": str(ROOT / library["lib"])})
        for library in providers)

    header = ROOT / "build/generated/sync_connectivity_config.h"
    content = "/* generated by generate_sync_connectivity_config.py */\n#pragma once\n"
    if available:
        content += "#define LAMBDA_HAVE_RTC 1\n"
    if header.is_file() and header.read_text() == content:
        return

    header.parent.mkdir(parents=True, exist_ok=True)
    scratch = ROOT / "temp"
    scratch.mkdir(exist_ok=True)
    with TemporaryDirectory(dir=scratch) as workspace:
        staged = Path(workspace) / header.name
        staged.write_text(content)
        staged.replace(header)


if __name__ == "__main__":
    main()
