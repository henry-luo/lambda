#!/usr/bin/env python3
"""Generate immutable NameRecord catalogs.  Use --check in CI."""
import argparse
import pathlib
import sys

from well_known_names_data import CSS_PROPERTY_SPELLINGS, MARKUP_ENTRY_SYMBOLS, POOLS

ROOT = pathlib.Path(__file__).resolve().parents[1]

def fnv1a(text):
    value = 2166136261
    for byte in text.encode("utf-8"):
        value ^= byte
        value = (value * 16777619) & 0xffffffff
    return value or 1

def render_header(pool, label, entries):
    guard = "WELL_KNOWN_%s_NAMES_H" % label.upper()
    prefix = {"markup":"MARKUP", "lambda":"LAMBDA", "js":"JS"}[label]
    identity_header = "../core/name_identity.h" if label == "js" else "name_identity.h"
    type_name = {"markup": "MarkupNameId", "lambda": "LambdaNameId", "js": "JsNameId"}[label]
    lines = ["// Generated by utils/generate_well_known_names.py; do not edit.",
             "#pragma once", "#include \"%s\"" % identity_header, "",
             "enum %s {" % type_name]
    for ordinal, entry in enumerate(entries, 1):
        symbol, _, kind = entry_parts(entry)
        enum_prefix = "%s_SYMBOL" % prefix if kind == "SYMBOL" else "%s_NAME" % prefix
        lines.append("    %s_%s = 0x%08Xu," % (enum_prefix, symbol, (pool << 16) | ordinal))
    lines += ["};", "", "extern const WellKnownNameRecord g_well_known_%s_names[];" % label,
              "extern const size_t g_well_known_%s_name_count;" % label, ""]
    return "\n".join(lines)

def render_source(pool, label, entries):
    header = "well_known_%s_names.h" % label if label != "js" else "js_well_known_names.h"
    rows = []
    for ordinal, entry in enumerate(entries, 1):
        _, spelling, kind = entry_parts(entry)
        encoded = spelling.encode("utf-8")
        if len(encoded) >= 127: raise ValueError("spelling too long: %s" % spelling)
        key_kind = "NAME_KEY_SYMBOL" if kind == "SYMBOL" else "NAME_KEY_STRING"
        rows.append("    {{ {{ 0x{hash:08X}u, UINT32_MAX, 0, {kind}, 0, 0x{id:08X}u }}, {length}u, 0x05u, \"{text}\" }},".format(
            hash=fnv1a(spelling), kind=key_kind, id=(pool << 16) | ordinal, length=len(encoded), text=spelling.replace('\\', '\\\\').replace('"', '\\"')))
    return "\n".join(["// Generated by utils/generate_well_known_names.py; do not edit.",
        "#include \"%s\"" % header, "", "const WellKnownNameRecord g_well_known_%s_names[] = {" % label,
        *rows, "};", "const size_t g_well_known_%s_name_count = sizeof(g_well_known_%s_names) / sizeof(g_well_known_%s_names[0]);" % (label,label,label), ""])

def css_property_symbol(spelling):
    return "CSS_PROPERTY_" + spelling.lstrip("-").upper().replace("-", "_").replace("*", "STAR")

def css_name_id_symbol(spelling):
    owner = MARKUP_ENTRY_SYMBOLS.get(spelling)
    if owner:
        return "MARKUP_NAME_" + owner
    return "MARKUP_NAME_CSS_" + spelling.lstrip("-").upper().replace("-", "_").replace("*", "STAR")

def render_css_property_mapping_header():
    lines = ["// Generated by utils/generate_well_known_names.py; do not edit.",
             "#pragma once", "#include \"../../core/well_known_markup_names.h\"", "",
             "// X(dense CssPropertyCode, generated NameId)",
             "#define WELL_KNOWN_CSS_PROPERTY_NAME_IDS(X) " + "\\"]
    for index, spelling in enumerate(CSS_PROPERTY_SPELLINGS):
        suffix = " " + "\\" if index + 1 < len(CSS_PROPERTY_SPELLINGS) else ""
        lines.append("    X(%s, %s)%s" % (css_property_symbol(spelling), css_name_id_symbol(spelling), suffix))
    lines.append("")
    return "\n".join(lines)

def all_catalog_entries():
    for pool, (_, entries) in POOLS.items():
        for ordinal, entry in enumerate(entries, 1):
            yield pool, ordinal, entry_parts(entry)

def lookup_capacity(entry_count):
    capacity = 1
    # Unsuccessful property-key probes dominate the LambdaJS workload.  The
    # minimum 0.70 load bound keeps the table compact but leaves linear-probe
    # clusters expensive enough to miss Tune11-D's measured probe target.
    while entry_count * 20 > capacity * 7:
        capacity <<= 1
    return capacity

def render_lookup_header():
    entries = list(all_catalog_entries())
    capacity = lookup_capacity(len(entries))
    slots = [0] * capacity
    max_probe = 0
    for pool, ordinal, (_, spelling, _) in entries:
        name_id = (pool << 16) | ordinal
        slot = fnv1a(spelling) & (capacity - 1)
        probe = 0
        while slots[slot] != 0:
            slot = (slot + 1) & (capacity - 1)
            probe += 1
            if probe >= capacity:
                raise ValueError("unable to place generated name lookup entry: %s" % spelling)
        slots[slot] = name_id
        max_probe = max(max_probe, probe)

    lines = ["// Generated by utils/generate_well_known_names.py; do not edit.",
             "#pragma once", "#include \"name_identity.h\"", "",
             "// Combined immutable lookup table: %d records, %d slots, max insertion probe %d." %
             (len(entries), capacity, max_probe),
             "static const NameId g_well_known_name_lookup[%d] = {" % capacity]
    for offset in range(0, capacity, 8):
        row = ", ".join("0x%08Xu" % value for value in slots[offset:offset + 8])
        lines.append("    %s," % row)
    lines += ["};", "static const size_t g_well_known_name_lookup_capacity = %d;" % capacity,
              "static const size_t g_well_known_name_lookup_max_probe = %d;" % max_probe, ""]
    return "\n".join(lines)

def outputs():
    for pool, (label, entries) in POOLS.items():
        base = ROOT / ("lambda/js" if label == "js" else "lambda/core")
        stem = "js_well_known_names" if label == "js" else "well_known_%s_names" % label
        yield base / (stem + ".h"), render_header(pool, label, entries)
        yield base / (stem + ".c"), render_source(pool, label, entries)
    yield ROOT / "lambda/input/css/well_known_css_property_mapping.h", render_css_property_mapping_header()
    yield ROOT / "lambda/core/well_known_name_lookup.h", render_lookup_header()

def entry_parts(entry):
    if len(entry) == 2:
        return entry[0], entry[1], "STRING"
    return entry

def validate_catalogs():
    seen_spellings = {}
    for pool, (_, entries) in POOLS.items():
        if pool not in (0, 1, 2):
            raise ValueError("invalid global name pool: %s" % pool)
        if len(entries) > 0xFFFF:
            raise ValueError("too many names in pool %s" % pool)
        for entry in entries:
            symbol, spelling, kind = entry_parts(entry)
            if kind not in ("STRING", "SYMBOL"):
                raise ValueError("invalid key kind for %s" % symbol)
            if not symbol or not spelling:
                raise ValueError("empty catalog symbol or spelling")
            prior = seen_spellings.get(spelling)
            if prior:
                raise ValueError("duplicate global spelling without an alias: %s" % spelling)
            seen_spellings[spelling] = symbol
    if len(CSS_PROPERTY_SPELLINGS) != len(set(CSS_PROPERTY_SPELLINGS)):
        raise ValueError("duplicate CSS property spelling")
    for spelling in CSS_PROPERTY_SPELLINGS:
        if spelling not in seen_spellings:
            raise ValueError("CSS property missing generated NameId: %s" % spelling)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    validate_catalogs()
    bad = False
    for path, content in outputs():
        if args.check:
            if not path.exists() or path.read_text() != content:
                print("stale generated file: %s" % path.relative_to(ROOT), file=sys.stderr)
                bad = True
        else:
            path.write_text(content)
    return 1 if bad else 0

if __name__ == "__main__":
    sys.exit(main())
