#!/usr/bin/env python3
"""Embed the trusted verifier closure; no ambient source selection at runtime."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ['security/tuf.ls', 'security/tuf/json.ls', 'security/tuf/metadata.ls',
           'security/tuf/delegation.ls', 'security/tuf/update.ls', 'security/tuf/path.ls',
           'security/tuf/_host.ls', 'io/utf8.ls', 'security/package_stage.ls',
           'security/tuf/_stage_host.ls']


def main():
    lines = ['// Generated by utils/generate_update_verifier.py; do not edit.', '#pragma once',
             'struct UpdateVerifierSource { const char* path; const unsigned char* bytes; size_t size; };']
    sizes = []
    for index, name in enumerate(SOURCES):
        data = (ROOT / 'lmd/package' / name).read_bytes(); sizes.append(len(data))
        lines.append(f'static const unsigned char update_source_{index}[] = {{')
        for first in range(0, len(data), 24):
            lines.append('    ' + ','.join(str(b) for b in data[first:first + 24]) + ',')
        lines.extend(['    0', '};'])
    lines.append('static const UpdateVerifierSource update_verifier_sources[] = {')
    for index, (name, size) in enumerate(zip(SOURCES, sizes)):
        lines.append(f'    {{"/lambda-update-verifier/package/{name}", update_source_{index}, {size}}},')
    lines.extend(['};', ''])
    output = ROOT / 'temp/generated/update_verifier_sources.h'
    text = '\n'.join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != text:
        output.write_text(text)


if __name__ == '__main__':
    main()
