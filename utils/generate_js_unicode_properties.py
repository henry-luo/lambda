#!/usr/bin/env python3
"""Generate shared JS Unicode property ranges from the pinned Test262 corpus."""

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent


def generate(source):
    properties = []
    versions = set()
    digest = hashlib.sha256()
    for path in sorted(source.glob('*.js')):
        text = path.read_text()
        version = re.search(r'Unicode v([\d.]+)', text)
        if not version:
            raise ValueError(f'missing Unicode version: {path}')
        versions.add(version[1])
        digest.update(path.name.encode() + b'\0' + path.read_bytes())
        body = re.search(r'const matchSymbols = buildString\(\{(.*?)\}\);', text, re.S)
        if not body:
            raise ValueError(f'missing property ranges: {path}')
        lone = re.search(r'loneCodePoints:\s*\[(.*?)\]', body[1], re.S)
        spans = re.search(r'ranges:\s*\[(.*)\]', body[1], re.S)
        ranges = [(int(cp, 16), int(cp, 16)) for cp in re.findall(r'0x([0-9A-Fa-f]+)', lone[1])]
        ranges += [(int(lo, 16), int(hi, 16)) for lo, hi in
                   re.findall(r'\[0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+)\]', spans[1])]
        merged = []
        for lo, hi in sorted(ranges):
            if lo > hi or hi > 0x10FFFF:
                raise ValueError(f'invalid property range: {path}')
            if merged and lo <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
            else:
                merged.append((lo, hi))
        aliases = sorted(set(re.findall(r'\\[pP]\{([^}]+)\}', text)))
        if not merged or not aliases:
            raise ValueError(f'empty property: {path}')
        name = re.sub(r'[^a-z0-9]+', '_', path.stem.lower())
        properties.append((name, merged, aliases))
    if len(versions) != 1:
        raise ValueError(f'inconsistent Unicode versions: {versions}')
    lines = [
        '// generated by utils/generate_js_unicode_properties.py; do not edit.',
        f'// Unicode {versions.pop()}; source SHA-256: {digest.hexdigest()}',
        '// source: ref/test262/test/built-ins/RegExp/property-escapes/generated/*.js',
        '// Test262 license: ref/test262/LICENSE.',
        'struct JsRegexGeneratedPropertyTable {',
        '    const char* name;',
        '    const JsRegexRange* ranges;',
        '    int count;',
        '};', '',
    ]
    tables = []
    for i, (name, ranges, aliases) in enumerate(properties):
        variable = f'js_regex_generated_ranges_{i}_{name}'
        lines.append(f'static const JsRegexRange {variable}[] = {{')
        entries = [f'{{0x{lo:06X},0x{hi:06X}}}' for lo, hi in ranges]
        lines += ['    ' + ','.join(entries[start:start + 5]) +
                  (',' if start + 5 < len(entries) else '')
                  for start in range(0, len(entries), 5)]
        lines += ['};', '']
        count = f'(int)(sizeof({variable}) / sizeof({variable}[0]))'
        tables += [f'    {{"{alias}", {variable}, {count}}},' for alias in aliases]
        if name in ('id_start', 'id_continue'):
            lines += [f'static const JsRegexRange* const js_unicode_{name}_ranges = {variable};',
                      f'static const int js_unicode_{name}_count = {count};', '']
    lines += ['static const JsRegexGeneratedPropertyTable js_regex_generated_property_tables[] = {']
    return '\n'.join(lines + tables + ['};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'ref/test262/test/built-ins/RegExp/property-escapes/generated')
    parser.add_argument('--output', type=Path, default=ROOT / 'lambda/js/js_regex_generated_property_tables.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.source)
    if args.check:
        if args.output.read_text() != result:
            raise SystemExit('JS Unicode property data differs; regenerate the include')
    else:
        args.output.write_text(result)
    print(f'JS_UNICODE_PROPERTIES: {"checked" if args.check else "generated"} {args.output}')


if __name__ == '__main__':
    main()
