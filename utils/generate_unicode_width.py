#!/usr/bin/env python3
"""Generate the inverse CSS full-width transform from UnicodeData.txt."""

import hashlib
from pathlib import Path
from unicode_generator import run_generator

ROOT = Path(__file__).resolve().parent.parent
VERSION = "17.0.0"
SOURCE_SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"


def generate(source):
    if hashlib.sha256(source.encode()).hexdigest() != SOURCE_SHA256:
        raise ValueError(f"expected the pinned Unicode {VERSION} UnicodeData.txt")
    records = [line.split(";") for line in source.splitlines() if line]
    mappings, canonical = {}, {}
    for record in records:
        cp, decomposition = int(record[0], 16), record[5].split()
        if decomposition[:1] == ["<wide>"]:
            mappings[cp] = tuple(int(part, 16) for part in decomposition[1:])
        elif decomposition[:1] == ["<narrow>"]:
            assert len(decomposition) == 2
            mappings[int(decomposition[1], 16)] = (cp,)
        elif decomposition and not decomposition[0].startswith("<"):
            canonical[cp] = tuple(int(part, 16) for part in decomposition)

    def nfd(cp):
        return sum((nfd(part) for part in canonical[cp]), ()) if cp in canonical else (cp,)

    # voiced kana need two narrow characters; do not apply unrelated compatibility decompositions.
    for cp in canonical:
        parts = nfd(cp)
        if cp not in mappings and all(part in mappings for part in parts):
            mappings[cp] = sum((mappings[part] for part in parts), ())
    assert mappings and max(map(len, mappings.values())) <= 3
    lines = [
        "// generated by utils/generate_unicode_width.py; do not edit.",
        f"// Unicode {VERSION} UnicodeData.txt; SHA-256: {hashlib.sha256(source.encode()).hexdigest()}",
        f"// source: https://www.unicode.org/Public/{VERSION}/ucd/UnicodeData.txt",
        "// Unicode data license: lib/UNICODE_LICENSE.txt (https://www.unicode.org/license.txt).",
        "static const UtfWidthMapping utf_halfwidth_mappings[] = {",
    ]
    lines.extend(f"    {{0x{cp:04X}, {{{', '.join(f'0x{part:04X}' for part in parts)}}}, {len(parts)}}},"
                 for cp, parts in sorted(mappings.items()))
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    run_generator(generate, __doc__, ROOT / "lib/utf_width_data.h", "UNICODE_WIDTH",
                  "Unicode width data differs; regenerate the header")
