#!/usr/bin/env node
// Extract the checked-in hyphen.js en-US tables into portable benchmark data.
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const textDir = __dirname;
const sourcePath = path.join(textDir, "hyphen.js");
const jsonPath = path.join(textDir, "hyphen_patterns.json");
const headerPath = path.join(textDir, "c2mir", "hyphen_patterns_data.h");
const source = fs.readFileSync(sourcePath, "utf8");
const fixtureStart = source.indexOf("var hyphen_texts = [");
if (fixtureStart < 0) throw new Error("missing hyphen benchmark fixture marker");

const context = {};
vm.createContext(context);
new vm.Script(source.slice(0, fixtureStart), {filename: sourcePath}).runInContext(context);
const patterns = context.hyphenation_patterns;
if (!Array.isArray(patterns) || !Array.isArray(patterns[0]) || !patterns[1]) {
  throw new Error("could not extract hyphenationPatternsEnUs data");
}

const nodes = [];
const edges = [];
function flattenTrie(value) {
  const index = nodes.length;
  const node = {level: -1, first: 0, count: 0};
  nodes.push(node);
  let children = value;
  if (Array.isArray(value)) {
    children = value[0];
    node.level = value[1];
  } else if (typeof value === "number") {
    node.level = value;
    children = null;
  }
  if (children && typeof children === "object") {
    const childEdges = [];
    for (const key of Object.keys(children)) {
      childEdges.push({code: key.charCodeAt(0), child: flattenTrie(children[key])});
    }
    node.first = edges.length;
    for (const edge of childEdges) edges.push(edge);
    node.count = childEdges.length;
  }
  return index;
}

const root = flattenTrie(patterns[1]);
const fixture = {levels: patterns[0], nodes, edges, root, exceptions: patterns[2] || {}};
fs.writeFileSync(jsonPath, JSON.stringify(fixture));

function formatArray(values, width) {
  const rows = [];
  for (let index = 0; index < values.length; index += width) {
    rows.push("    " + values.slice(index, index + width).join(", "));
  }
  return rows.join(",\n");
}

const levelOffsets = [];
const levelLengths = [];
const levelValues = [];
for (const level of patterns[0]) {
  levelOffsets.push(levelValues.length);
  levelLengths.push(level.length);
  levelValues.push(...level);
}
const exceptionWords = Object.keys(patterns[2] || {});
const exceptionMarkers = exceptionWords.map((word) => patterns[2][word]);
const maxExceptionMarkers = Math.max(1, ...exceptionMarkers.map((markers) => markers.length));
const exceptionRows = exceptionMarkers.map((markers) =>
  "    {" + markers.concat(Array(maxExceptionMarkers - markers.length).fill(0)).join(", ") + "}");
const escapedWords = exceptionWords.map((word) => `    "${word}"`).join(",\n");

const header = [
  "/* Generated by test/benchmark/text/generate_hyphen_fixture.js. */",
  "#ifndef BENCHMARK_HYPHEN_PATTERNS_DATA_H",
  "#define BENCHMARK_HYPHEN_PATTERNS_DATA_H",
  "",
  `#define HYPHEN_LEVEL_COUNT ${patterns[0].length}`,
  `#define HYPHEN_LEVEL_VALUE_COUNT ${levelValues.length}`,
  `#define HYPHEN_TRIE_NODE_COUNT ${nodes.length}`,
  `#define HYPHEN_TRIE_EDGE_COUNT ${edges.length}`,
  `#define HYPHEN_TRIE_ROOT ${root}`,
  `#define HYPHEN_EXCEPTION_COUNT ${exceptionWords.length}`,
  `#define HYPHEN_EXCEPTION_MARKER_CAPACITY ${maxExceptionMarkers}`,
  "",
  "static const unsigned short hyphen_level_offsets[HYPHEN_LEVEL_COUNT] = {",
  formatArray(levelOffsets, 16),
  "};",
  "static const unsigned char hyphen_level_lengths[HYPHEN_LEVEL_COUNT] = {",
  formatArray(levelLengths, 24),
  "};",
  "static const unsigned char hyphen_level_values[HYPHEN_LEVEL_VALUE_COUNT] = {",
  formatArray(levelValues, 32),
  "};",
  "static const unsigned short hyphen_node_first[HYPHEN_TRIE_NODE_COUNT] = {",
  formatArray(nodes.map((node) => node.first), 16),
  "};",
  "static const unsigned char hyphen_node_count[HYPHEN_TRIE_NODE_COUNT] = {",
  formatArray(nodes.map((node) => node.count), 24),
  "};",
  "static const short hyphen_node_level[HYPHEN_TRIE_NODE_COUNT] = {",
  formatArray(nodes.map((node) => node.level), 20),
  "};",
  "static const unsigned char hyphen_edge_code[HYPHEN_TRIE_EDGE_COUNT] = {",
  formatArray(edges.map((edge) => edge.code), 24),
  "};",
  "static const unsigned short hyphen_edge_child[HYPHEN_TRIE_EDGE_COUNT] = {",
  formatArray(edges.map((edge) => edge.child), 16),
  "};",
  "static const char *const hyphen_exception_words[HYPHEN_EXCEPTION_COUNT] = {",
  escapedWords,
  "};",
  "static const unsigned char hyphen_exception_counts[HYPHEN_EXCEPTION_COUNT] = {",
  formatArray(exceptionMarkers.map((markers) => markers.length), 16),
  "};",
  "static const unsigned char hyphen_exception_markers[HYPHEN_EXCEPTION_COUNT][HYPHEN_EXCEPTION_MARKER_CAPACITY] = {",
  exceptionRows.join(",\n"),
  "};",
  "",
  "#endif",
  ""
].join("\n");
fs.writeFileSync(headerPath, header);
