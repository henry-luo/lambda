#!/usr/bin/env node
// Generate the jq_* benchmark fixtures:
// - jq/orders.json: the jq_records input, a port of the jq expression in
//   vibe/impl/Lambda_Impl_Jq_Tests.md Appendix A.2 (same values, same order);
// - jq/jq_helper.js: the vendored jqjs with its ES `export` lines removed,
//   followed by jq/jq_driver.js, so one script-mode file serves Node's
//   require() and the runner's @benchmark-include bundling for LambdaJS.
// Regenerate after changing jq/vendor/jqjs.js or jq/jq_driver.js.
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "jq");
const regions = ["us-east", "eu-west", "ap-south", null];
const statuses = ["paid", "refunded", "pending"];

const orders = [];
for (let i = 0; i < 4000; i++) {
    const tags = [];
    for (let t = 0; t < i % 4; t++) tags.push("t" + t);
    const items = [];
    for (let k = 0; k < i % 5 + 1; k++) {
        items.push({sku: "S" + ((i * 7 + k) % 50), qty: k + 1,
            price: ((i * 13 + k * 17) % 1000) / 10});
    }
    orders.push({id: i, user: {name: "user" + (i % 97), region: regions[i % 4], tags},
        items, status: statuses[i % 3], note: i % 11 === 0 ? "bad" : null});
}
fs.writeFileSync(path.join(dir, "orders.json"), JSON.stringify(orders) + "\n");

const jqjs = fs.readFileSync(path.join(dir, "vendor", "jqjs.js"), "utf8");
const exportLines = jqjs.split("\n").filter(line => /^export\b/.test(line));
if (exportLines.length !== 2) throw new Error("unexpected jqjs export lines: " + exportLines.length);
const script = jqjs.split("\n").filter(line => !/^export\b/.test(line)).join("\n");
const driver = fs.readFileSync(path.join(dir, "jq_driver.js"), "utf8");
fs.writeFileSync(path.join(dir, "jq_helper.js"),
    "// GENERATED by generate_jq_fixture.js from jq/vendor/jqjs.js + jq/jq_driver.js; do not edit.\n" +
    script + "\n" + driver);
