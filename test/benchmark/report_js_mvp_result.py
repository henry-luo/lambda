#!/usr/bin/env python3
"""Validate and render independent JS MVP versus QuickJS release sessions."""

import argparse
import json
import math
import os
import statistics
import sys


SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))
MANIFEST_PATH = os.path.join(SCRIPT_DIR, "js_mvp_manifest_v1.json")


def geomean(values):
    return math.exp(sum(math.log(value) for value in values) / len(values))


def median(values):
    return statistics.median(values)


def load_manifest():
    with open(MANIFEST_PATH, encoding="utf-8") as stream:
        manifest = json.load(stream)
    workloads = manifest.get("workloads")
    if manifest.get("schema") != 2 or not isinstance(workloads, list) or len(workloads) != 63:
        raise ValueError("expected schema-2 manifest with 63 workloads")
    return workloads


def required_row(session, identifier):
    suite, name = identifier.split("/", 1)
    row = session.get(suite, {}).get(name)
    if not isinstance(row, dict):
        raise ValueError("missing canonical row " + identifier)
    return row


def checked_engine_value(row, engine, identifier):
    status = row.get("_status", {}).get(engine)
    detail = row.get("_status_detail", {}).get(engine, {})
    samples = detail.get("samples")
    if status != "ok" or not isinstance(samples, list) or len(samples) != 3:
        raise ValueError(identifier + " " + engine + " does not have three successful samples")
    if any(sample.get("status") != "ok" or sample.get("exec_ms") is None for sample in samples):
        raise ValueError(identifier + " " + engine + " has a failed or un-timed sample")
    value = row.get(engine)
    if not isinstance(value, (int, float)) or value <= 0:
        raise ValueError(identifier + " " + engine + " has no positive median execution time")
    return float(value), [float(sample["exec_ms"]) for sample in samples]


def read_session(path, workloads):
    with open(path, encoding="utf-8") as stream:
        session = json.load(stream)
    metadata = session.get("_metadata", {})
    if metadata.get("mode") != "time" or metadata.get("runs") != 3:
        raise ValueError(path + " is not a three-run time session")
    engines = metadata.get("engines", [])
    if engines != ["mvpjs", "quickjs"]:
        raise ValueError(path + " must contain the ordered MVP/QuickJS engine pair")

    rows = []
    for workload in workloads:
        identifier = workload["id"]
        row = required_row(session, identifier)
        mvp_ms, mvp_samples = checked_engine_value(row, "mvpjs", identifier)
        qjs_ms, qjs_samples = checked_engine_value(row, "quickjs", identifier)
        rows.append({
            "id": identifier,
            "mvp_ms": mvp_ms,
            "quickjs_ms": qjs_ms,
            "ratio": mvp_ms / qjs_ms,
            "mvp_samples_ms": mvp_samples,
            "quickjs_samples_ms": qjs_samples,
        })
    return {"path": path, "metadata": metadata, "rows": rows,
            "geomean_ratio": geomean([row["ratio"] for row in rows])}


def format_ms(value):
    return f"{value:.6g}"


def session_summary(session):
    meta = session["metadata"]
    return {
        "path": session["path"],
        "started_at": meta.get("started_at"),
        "finished_at": meta.get("finished_at"),
        "lambda_commit": meta.get("lambda_commit"),
        "lambda_exe_sha256": meta.get("lambda_exe_sha256"),
        "quickjs_version": meta.get("quickjs_version"),
        "quickjs_exe_sha256": meta.get("quickjs_exe_sha256"),
        "platform": meta.get("platform"),
        "ratio": session["geomean_ratio"],
    }


def render_markdown(sessions, max_ratio):
    lines = [
        "# JS MVP Release Acceptance",
        "",
        "Generated by `test/benchmark/report_js_mvp_result.py` from fresh standard-runner JSON.",
        "Each cell is the median execution time in milliseconds from three isolated process runs.",
        "All 63 manifest rows have three `ok` samples for both engines.",
        "",
        "| Session | MVP / QuickJS geometric mean | Target | Result |",
        "|---|---:|---:|---|",
    ]
    for index, session in enumerate(sessions, 1):
        ratio = session["geomean_ratio"]
        result = "PASS" if ratio <= max_ratio else "FAIL"
        lines.append(f"| {index} | {ratio:.6f}x | <= {max_ratio:.2f}x | {result} |")
    lines.extend(["", "## Session provenance", "",
        "| Session | Started | Finished | Commit | QuickJS | Platform |",
        "|---|---|---|---|---|---|"])
    for index, session in enumerate(sessions, 1):
        meta = session["metadata"]
        lines.append("| {} | {} | {} | {} | {} | {} |".format(
            index, meta.get("started_at", ""), meta.get("finished_at", ""),
            meta.get("lambda_commit", ""), meta.get("quickjs_version", ""),
            meta.get("platform", "")))
    lines.extend(["", "## Per-row execution medians", "",
        "| Workload | MVP session 1 | QuickJS session 1 | Ratio 1 | MVP session 2 | QuickJS session 2 | Ratio 2 |",
        "|---|---:|---:|---:|---:|---:|---:|"])
    for row_index, first in enumerate(sessions[0]["rows"]):
        cells = [first["id"], format_ms(first["mvp_ms"]), format_ms(first["quickjs_ms"]),
                 f"{first['ratio']:.6f}"]
        for session in sessions[1:]:
            row = session["rows"][row_index]
            cells.extend([format_ms(row["mvp_ms"]), format_ms(row["quickjs_ms"]),
                          f"{row['ratio']:.6f}"])
        lines.append("| " + " | ".join(cells) + " |")
    lines.extend(["", "## Interpretation", "",
        "The acceptance metric assigns equal logarithmic weight to each canonical workload:",
        "`exp(sum(log(MVP_i / QuickJS_i)) / 63)`. There is no per-row speed threshold;",
        "all rows remain reported above. This report validates the timed self-check workflow",
        "used by the standard runner. It does not claim full ECMAScript conformance.",
        ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--session", action="append", required=True,
                        help="fresh three-run MVP/QuickJS JSON; supply at least two for acceptance")
    parser.add_argument("--output", required=True, help="generated Markdown output path")
    parser.add_argument("--json-output", required=True, help="generated machine-readable summary")
    parser.add_argument("--max-ratio", type=float, default=0.80)
    args = parser.parse_args()
    if len(args.session) < 2:
        parser.error("acceptance requires two independent sessions")
    if args.max_ratio <= 0:
        parser.error("--max-ratio must be positive")

    os.chdir(PROJECT_ROOT)
    try:
        workloads = load_manifest()
        sessions = [read_session(path, workloads) for path in args.session]
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print("JS MVP result validation failed: " + str(error), file=sys.stderr)
        return 1

    summary = {
        "schema": 1,
        "manifest": os.path.relpath(MANIFEST_PATH, PROJECT_ROOT),
        "target_ratio": args.max_ratio,
        "sessions": [session_summary(session) for session in sessions],
        "accepted": all(session["geomean_ratio"] <= args.max_ratio for session in sessions),
    }
    with open(args.json_output, "w", encoding="utf-8") as stream:
        json.dump(summary, stream, indent=2)
        stream.write("\n")
    with open(args.output, "w", encoding="utf-8") as stream:
        stream.write(render_markdown(sessions, args.max_ratio))
    if not summary["accepted"]:
        print("JS MVP release target failed", file=sys.stderr)
        return 1
    print("JS MVP release target passed across {} sessions".format(len(sessions)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
