const path = require('path');
const esbuild = require('esbuild');
const expected = require('./package.json').devDependencies.esbuild;
if (esbuild.version !== expected) throw new Error(`Expected esbuild ${expected}; run npm ci in test/js/react`);

esbuild.buildSync({
  absWorkingDir: __dirname,
  entryPoints: ['suite.jsx'],
  outfile: '../react.js',
  bundle: true,
  platform: 'browser',
  format: 'iife',
  jsx: 'automatic',
  define: {'process.env.NODE_ENV': '"production"'},
  minify: true,
  legalComments: 'eof',
  banner: {js: '// React 19.3.1 compatibility tests. Generated by test/js/react/build.cjs; edit react/suite.jsx.'},
  nodePaths: (process.env.NODE_PATH || '').split(path.delimiter).filter(Boolean)
});
