const path = require('path');
const fs = require('fs');
const esbuild = require('esbuild');
const expected = require('./package.json').devDependencies.esbuild;
if (esbuild.version !== expected) throw new Error(`Expected esbuild ${expected}; run npm ci in test/js/react`);

const packages = require('./package.json').dependencies;
const suites = [
  ['react', 'suite.jsx', 'React ' + packages.react],
  ['redux_toolkit', 'redux_toolkit.js', 'Redux Toolkit ' + packages['@reduxjs/toolkit']],
  ['react_redux', 'react_redux.jsx', 'React Redux ' + packages['react-redux']],
  ['zustand', 'zustand.jsx', 'Zustand ' + packages.zustand],
  ['react_router', 'react_router.jsx', 'React Router ' + packages['react-router']]
];

const upstream = new Set();
for (const [name, source, label] of suites) {
  const result = esbuild.buildSync({
    absWorkingDir: __dirname,
    entryPoints: [source],
    outfile: '../' + name + '.js',
    bundle: true,
    platform: 'browser',
    format: 'iife',
    jsx: 'automatic',
    define: {'process.env.NODE_ENV': '"production"'},
    minify: true,
    legalComments: 'eof',
    metafile: true,
    banner: {js: '// ' + label + ' compatibility tests. Generated by test/js/react/build.cjs; edit react/' + source + '.'},
    nodePaths: (process.env.NODE_PATH || '').split(path.delimiter).filter(Boolean)
  });
  for (const input of Object.keys(result.metafile.inputs)) {
    const absolute = path.resolve(__dirname, input);
    const marker = path.sep + 'node_modules' + path.sep;
    const at = absolute.lastIndexOf(marker);
    if (at < 0) continue;
    const parts = absolute.slice(at + marker.length).split(path.sep);
    const count = parts[0].startsWith('@') ? 2 : 1;
    upstream.add(absolute.slice(0, at + marker.length) + parts.slice(0, count).join(path.sep));
  }
}

const notices = [...upstream].sort().map(directory => {
  const metadata = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
  const license = fs.readdirSync(directory).find(name => /^licen[cs]e(?:\.|$)/i.test(name));
  if (!license) throw new Error('Missing upstream license: ' + metadata.name);
  return metadata.name + ' ' + metadata.version + '\n' + fs.readFileSync(path.join(directory, license), 'utf8').trim();
});
fs.writeFileSync(path.join(__dirname, 'THIRD_PARTY_LICENSES.txt'), notices.join('\n\n---\n\n') + '\n');
