const path = require('path');
const fs = require('fs');
const {createRequire} = require('module');

module.exports = function buildLibraryFixtures(directory, suites) {
  const localRequire = createRequire(path.join(directory, 'package.json'));
  const esbuild = localRequire('esbuild');
  const metadata = localRequire('./package.json');
  const expected = metadata.devDependencies.esbuild;
  if (esbuild.version !== expected) throw new Error(`Expected esbuild ${expected}; run npm ci in ${directory}`);
  const upstream = new Set();
  for (const [name, source, label] of suites) {
    const result = esbuild.buildSync({
      absWorkingDir: directory,
      entryPoints: [source],
      outfile: '../' + name + '.js',
      bundle: true,
      platform: 'browser',
      format: 'iife',
      jsx: 'automatic',
      define: {'process.env.NODE_ENV': '"production"'},
      minify: true,
      legalComments: 'eof',
      metafile: true,
      banner: {js: '// ' + label + ' compatibility tests. Generated by test/js/' + path.basename(directory) + '/build.cjs; edit ' + path.basename(directory) + '/' + source + '.'},
      nodePaths: (process.env.NODE_PATH || '').split(path.delimiter).filter(Boolean)
    });
    for (const input of Object.keys(result.metafile.inputs)) {
      const absolute = path.resolve(directory, input);
      const marker = path.sep + 'node_modules' + path.sep;
      const at = absolute.lastIndexOf(marker);
      if (at < 0) continue;
      const parts = absolute.slice(at + marker.length).split(path.sep);
      const count = parts[0].startsWith('@') ? 2 : 1;
      upstream.add(absolute.slice(0, at + marker.length) + parts.slice(0, count).join(path.sep));
    }
  }
  const notices = [...upstream].sort().map(directory => {
    const metadata = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
    const license = fs.readdirSync(directory).find(name => /^licen[cs]e(?:\.|$)/i.test(name));
    const fallback = localRequire('./package.json').upstreamLicenses?.[metadata.name];
    if (!license && !fallback) throw new Error('Missing upstream license: ' + metadata.name);
    return metadata.name + ' ' + metadata.version + '\n' + fs.readFileSync(license ? path.join(directory, license) : path.resolve(localRequire.resolve('./package.json'), '..', fallback), 'utf8').trim();
  });
  fs.writeFileSync(path.join(directory, 'THIRD_PARTY_LICENSES.txt'), notices.join('\n\n---\n\n') + '\n');
};
