#!/usr/bin/env python3
"""Deterministic synthetic Lambda scripts for the T0 turnaround measurement.

Corpus item C2 of vibe/Lambda_Impl_Ast_Interp.md §6.1: run-once straight-line
code at 1k / 5k / 20k lines, which is where compile cost dominates by
construction. Every construct stays inside the P0 walker subset so the scripts
interpret end to end (fallback=0).

All output goes under ./temp/ (CLAUDE rule 2).
"""
import argparse
import os

SIZES = (1000, 5000, 20000)


def generate(lines: int) -> str:
    # Deterministic by construction: no RNG, no timestamps. Every statement is
    # a distinct binding so the frame plan has real work to do, and one value
    # expression per 25 lines keeps the result small enough to print.
    out = ["// generated by test/interp/gen_bench.py — do not edit",
           "let seed = 7"]
    prev = "seed"
    for i in range(lines):
        name = f"v{i}"
        op = ("+", "-", "*")[i % 3]
        out.append(f"let {name} = ({prev} {op} {i % 97 + 1}) + {i % 13}")
        prev = name
    out.append(prev)
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default="temp/interp_bench")
    ap.add_argument("--sizes", type=int, nargs="*", default=list(SIZES))
    args = ap.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    written = []
    for size in args.sizes:
        path = os.path.join(args.out_dir, f"gen_{size}.ls")
        with open(path, "w") as f:
            f.write(generate(size))
        written.append(path)
    for path in written:
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
